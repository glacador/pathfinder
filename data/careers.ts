export function matchCareers(
  userScores: Record<AptitudeId, number>
): { career: Career; matchScore: number }[] {
  return CAREERS.map((career) => {
    let matchScore = 0;
    let totalWeight = 0;

    Object.entries(career.aptitudeProfile).forEach(([aptitude, importance]) => {
      const userScore = userScores[aptitude as AptitudeId] || 50;
      const weight = importance;
      const normalizedUser = userScore / 10;
      const diff = Math.abs(normalizedUser - importance);
      const match = Math.max(0, 10 - diff) / 10;

      matchScore += match * weight;
      totalWeight += weight;
    });

    return {
      career,
      matchScore: Math.round((matchScore / totalWeight) * 100),
    };
  }).sort((a, b) => b.matchScore - a.matchScore);
}

export function getCareerById(id: string): Career | undefined {
  return CAREERS.find((c) => c.id === id);
}

export function getCareersByCategory(category: string): Career[] {
  return CAREERS.filter((c) => c.category === category);
}
